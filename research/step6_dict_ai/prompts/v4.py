"""提示词 v4 = v3 + 分组权收归程序（2026-09-26）。
动机：dev 上 v3「可放行」的 14 个错全是模型把不同的字并进一组（己/已/巳 8、雎/睢、傅/傳…），图像又恰好选了组里另一个字。
改法：候选按严格异体分好组（dictlib.group_cands strict）；模型**只能拆组、不得并组**；形近而不同的字必须分属不同组、各给 p。
程序在打分时另查「并组」（harness.score 的 merged），并组即视为模型没判出来。"""
from . import v3
VERSION = 'v4-2026-09-26'
SYSTEM = v3.SYSTEM.replace(
    '候選已按詞典預先分成「關聯組」：同組的字在詞典裡互為異體、古今字、簡繁或俗正（含經同一個字間接相連）。詞典關聯有噪聲（例如「义」既是「義」的簡體又是「叉」的古寫，會把兩個詞連到一組），所以你可以拆組，但須說明理由。',
    '候選已按詞典預先分成「關聯組」（A組、B組…）：同組的字經至少兩部字書認定互為異體、古今字、簡繁或俗正，是**同一個字的不同寫法**。不同組就是**不同的字**，哪怕字形極近（己／已／巳、傅／傳、雎／睢、土／士、未／末、日／曰）或意思相通（通假字也算不同的字）。'
).replace(
    '2. 分組（groups）：把保留的候選按「在此處表示的是同一個詞」分組；每組給出此處是該詞的概率 p（各組 p 之和為 1），並說明理由。',
    '2. 分組（groups）：**沿用程序給的關聯組，不得把不同組的字併進同一組**。即使兩個不同的字在此處都講得通、或你分不清，也要分列兩組、各給概率 p（各組 p 之和為 1），讓後續按概率處理；把它們併成一組等於沒有作答。你可以把一個關聯組拆開（詞典有誤連時），須說明理由。'
)
def build(*args, **kw):
    msgs, marks = v3.build(*args, **kw)
    msgs[0] = {'role': 'system', 'content': SYSTEM}
    return msgs, marks
